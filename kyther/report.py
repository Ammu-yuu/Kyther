    MAX_ROWS_PER_GROUP = 50  # keep the report readable; low-confidence noise is capped

    def _platform_from_url(self, url: str) -> str:
        """github.com/torvalds -> 'Github'; falls back cleanly on odd URLs."""
        host = urlsplit(url if "//" in url else "//" + url).netloc.lower().split(":")[0]
        labels = [l for l in host.split(".") if l]
        label = labels[-2] if len(labels) >= 2 else (labels[0] if labels else host)
        return label.capitalize() or host

    def _dedupe_accounts(self):
        """One row per host, keeping the highest-confidence source when duplicated."""
        best: dict[str, dict] = {}
        for f in self.scan.get("findings", []):
            if f.get("category") != "accounts":
                continue
            for p in f.get("data", {}).get("profiles", []):
                host = urlsplit(p["url"]).netloc.replace("www.", "").lower() or p["url"]
                conf = p.get("confidence", "possible")
                cur = best.get(host)
                if cur is None or CONF_RANK.get(conf, 0) > CONF_RANK.get(cur.get("confidence", "possible"), 0):
                    best[host] = {**p, "confidence": conf}
        return list(best.values())

    def findings_accounts(self):
        accounts = self._dedupe_accounts()
        els = [Paragraph("Findings · Accounts", self.s["h2"])]
        if not accounts:
            els.append(Paragraph("No accounts found.", self.s["body"]))
            return els

        sources = sum(1 for f in self.scan.get("findings", []) if f.get("category") == "accounts")
        els.append(Paragraph(
            f"{len(accounts)} unique accounts across {sources} source(s), grouped by "
            "confidence. Weight is each account's contribution to the footprint factor.",
            self.s["body"]))

        groups = {c: [] for c in CONF_ORDER}
        for a in accounts:
            groups.setdefault(a.get("confidence", "possible"), []).append(a)

        for level in CONF_ORDER:
            rows = sorted(groups[level], key=lambda a: (a.get("platform") or "").lower())
            if not rows:
                continue
            fill, text, glyph = CONF_STYLE[level]
            shown = rows[: self.MAX_ROWS_PER_GROUP]

            els.append(Spacer(1, 0.14 * inch))
            gh = ParagraphStyle("gh", parent=self.s["body"], fontName=FONT_TITLE,
                                fontSize=10, textColor=text, spaceAfter=4)
            els.append(Paragraph(f"{glyph} {level.upper()} ({len(rows)}) — {CONF_DESC[level]}", gh))

            data = [["Platform", "URL", "Weight"]]
            for a in shown:
                plat = a.get("platform") or self._platform_from_url(a["url"])
                url = a["url"].split("//", 1)[-1].replace("www.", "")
                if len(url) > 52:
                    url = url[:51] + "…"
                data.append([plat, url, CONF_WEIGHT.get(a.get("confidence"), "")])

            t = Table(data, colWidths=[1.55 * inch, 3.95 * inch, 0.65 * inch], repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), fill),          # header row = confidence tint
                ("TEXTCOLOR", (0, 0), (-1, 0), text),
                ("FONT", (0, 0), (-1, 0), FONT_TITLE, 7.5),
                ("LINEBELOW", (0, 0), (-1, 0), 0.7, text),
                ("FONT", (0, 1), (0, -1), FONT_BODY, 8.5),       # platform
                ("TEXTCOLOR", (0, 1), (0, -1), INK),
                ("FONT", (1, 1), (1, -1), FONT_MONO, 7.5),       # url
                ("TEXTCOLOR", (1, 1), (1, -1), MUTED),
                ("FONT", (2, 1), (2, -1), FONT_MONO, 8),         # weight
                ("TEXTCOLOR", (2, 1), (2, -1), text),
                ("ALIGN", (2, 0), (2, -1), "RIGHT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#faf9fc")]),
                ("LINEBELOW", (0, 1), (-1, -2), 0.25, HAIRLINE),
                ("TOPPADDING", (0, 0), (-1, -1), 3.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
                ("LEFTPADDING", (0, 0), (-1, -1), 7),
                ("RIGHTPADDING", (0, 0), (-1, -1), 7),
            ]))
            els.append(t)
            if len(rows) > len(shown):
                els.append(Paragraph(
                    f"… and {len(rows) - len(shown)} more {level} accounts (omitted for brevity).",
                    ParagraphStyle("note", parent=self.s["body"], fontSize=7.5,
                                   textColor=MUTED, spaceBefore=3)))
        return els

    def _badge(self, level: str):
        """Color-coded confidence pill for a table cell."""
        _, text, glyph = CONF_STYLE.get(level, CONF_STYLE["possible"])
        return Paragraph(f'<font color="{_hexstr(text)}"><b>{glyph} {level.upper()}</b></font>',
                         ParagraphStyle("badge", parent=self.s["body"], fontSize=7.5, leading=10))

    def _other_findings(self):
        """Rows of (type, detail, source, confidence) for identity/contact findings."""
        d = self.scan.get("dossier") or {}
        rows = []
        for e in d.get("emails", []):
            raw = e.get("source")
            src = {"seed": "Search input", "hunter": "Hunter.io",
                   None: "GitHub commits"}.get(raw, raw or "GitHub commits")
            level = "probable" if raw == "hunter" else "confirmed"
            detail = self._anonymize(e["email"], "email") + (" (noreply)" if e.get("noreply") else "")
            rows.append(("Email", detail, src, level))
        if d.get("primary_name"):
            rows.append(("Name", d["primary_name"], "Profile enrichment", "confirmed"))
        for loc in (d.get("locations") or [])[:2]:
            rows.append(("Location", loc, "Profile enrichment", "confirmed"))
        for co in (d.get("companies") or [])[:2]:
            rows.append(("Employer", co, "Profile enrichment", "confirmed"))
        for f in self.scan.get("findings", []):
            if f.get("analyzer") == "phone_intel":
                pd = f.get("data", {})
                detail = self._anonymize(pd.get("e164") or self.scan["seed"]["value"], "phone")
                extra = " · ".join(x for x in (pd.get("location"), pd.get("line_type")) if x)
                rows.append(("Phone", f"{detail} ({extra})" if extra else detail,
                             "libphonenumber", "confirmed"))
        return rows

    def findings_other(self):
        rows = self._other_findings()
        els = [Paragraph("Findings · Identity &amp; Contact", self.s["h2"])]
        if not rows:
            els.append(Paragraph("No identity or contact findings.", self.s["body"]))
            return els

        data = [["Type", "Detail", "Source", "Confidence"]]
