# ── Page decorations: diagonal SAMPLE watermark + "Page n of N" footer ───────
class NumberedCanvas(canvas.Canvas):
    footer = "Kyther OSINT Assessment"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self._decorate(total)
            super().showPage()
        super().save()

    def _decorate(self, total):
        w, h = letter
        self.saveState()  # watermark
        self.setFont("Helvetica-Bold", 96)
        self.setFillColor(colors.Color(0, 0, 0, alpha=0.05))
        self.translate(w / 2.0, h / 2.0)
        self.rotate(45)
        self.drawCentredString(0, -34, "SAMPLE")
        self.restoreState()
        self.saveState()  # footer
        self.setFont("Helvetica", 7)
        self.setFillColor(MUTED)
        self.drawString(0.85 * inch, 0.5 * inch, self.footer)
        self.drawRightString(w - 0.85 * inch, 0.5 * inch,
                             "Page %d of %d" % (self._pageNumber, total))
        self.restoreState()


# ── The Kyther wings mark, drawn as vector (no image/svglib dependency) ──────
_WINGS = [
    [("m", 382, 292), ("c", 268, 300, 158, 366, 122, 452), ("c", 165, 470, 300, 436, 398, 400)],
    [("m", 452, 300), ("c", 566, 306, 652, 372, 690, 448), ("c", 655, 470, 528, 440, 458, 404)],
    [("m", 398, 225), ("l", 398, 612)],
    [("m", 402, 392), ("l", 540, 258)],
    [("m", 406, 400), ("l", 536, 600)],
]


class WingsLogo(Flowable):
    def __init__(self, width=84):
        super().__init__()
        self.width = width
        self.height = width * 425 / 620
        self.hAlign = "CENTER"

    def wrap(self, aw, ah):
        return (self.width, self.height)

    def draw(self):
        c = self.canv
        vx0, vy0, vw, vh = 95, 205, 620, 425

        def M(x, y):
            return ((x - vx0) / vw * self.width, (1 - (y - vy0) / vh) * self.height)

        c.setStrokeColor(PURPLE_LT)
        c.setLineWidth(max(1.4, self.width * 0.028))
        c.setLineCap(1)
        c.setLineJoin(1)
        for path in _WINGS:
            p = c.beginPath()
            for seg in path:
                if seg[0] == "m":
                    p.moveTo(*M(seg[1], seg[2]))
                elif seg[0] == "l":
                    p.lineTo(*M(seg[1], seg[2]))
                else:  # cubic
                    a, b, d = M(seg[1], seg[2]), M(seg[3], seg[4]), M(seg[5], seg[6])
                    p.curveTo(a[0], a[1], b[0], b[1], d[0], d[1])
            c.drawPath(p)


