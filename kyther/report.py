class Report:
    def __init__(self, scan: dict, anonymize: bool = True):
        self.scan = scan
        self.anonymize = anonymize
        self.now = datetime.now(timezone.utc)
        self.s = self._styles()

    # -- helpers --
    def _styles(self):
        base = getSampleStyleSheet()["Normal"]

        def st(name, **kw):
            return ParagraphStyle(name, parent=base, **kw)

        return {
            "title": st("title", fontName=FONT_TITLE, fontSize=34, textColor=PURPLE,
                        alignment=TA_CENTER, leading=38, spaceAfter=2, tracking=4),
            "subtitle": st("subtitle", fontName=FONT_BODY, fontSize=12, textColor=MUTED,
                           alignment=TA_CENTER, leading=16),
            "disclaimer": st("disclaimer", fontName=FONT_BODY, fontSize=6.5, textColor=MUTED,
                             alignment=TA_CENTER, leading=9.5),
            "h2": st("h2", fontName=FONT_TITLE, fontSize=13, textColor=PURPLE,
                     spaceBefore=8, spaceAfter=9),
            "body": st("body", fontName=FONT_BODY, fontSize=9.5, textColor=INK, leading=14),
            "meta": st("meta", fontName=FONT_BODY, fontSize=10, textColor=INK, leading=14),
            "mono": st("mono", fontName=FONT_MONO, fontSize=6.5, textColor=INK, leading=8.5),
            "chip": st("chip", fontName=FONT_BODY, fontSize=8, textColor=INK, leading=15),
            "label": st("label", fontName=FONT_TITLE, fontSize=8, textColor=MUTED,
                        leading=11, spaceBefore=10, spaceAfter=6),
        }

    def _anonymize(self, value: str, type: str) -> str:
        """Redact email/phone; show username/handle (low-sensitivity, pseudonymous)."""
        if not self.anonymize or type in ("username", "person", "company"):
            return value
        if type == "email":
            local, _, dom = value.partition("@")
            tld = dom.rsplit(".", 1)[-1] if "." in dom else dom
            return f"{local[:1]}•••@•••.{tld}"
        if type == "phone":
            digits = [c for c in value if c.isdigit()]
            return "•••-•••-" + "".join(digits[-4:]) if len(digits) >= 4 else "•••"
        return (value[:1] + "•••" + value[-1:]) if len(value) > 2 else "•••"

    def _case_ref(self) -> str:
        h = hashlib.sha1(self.scan["seed"]["value"].encode()).hexdigest()[:4].upper()
        return f"KY-{self.now:%Y%m%d}-{h}"

