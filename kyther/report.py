    @staticmethod
    def _redact_scalar(s: str) -> str:
        if _EMAIL_RE.match(s):
            return "***@***.***"
        if _URL_RE.match(s):
            return "***"
        digits = re.sub(r"\D", "", s)
        if s.strip().startswith("+") and len(digits) >= 7:  # E.164-ish phone
            return "***"
        return s

    def _redact_json(self, obj):
        """Deep copy with email / URL / phone values masked; usernames & names kept
        (same policy as _anonymize)."""
        if isinstance(obj, dict):
            return {k: self._redact_json(v) for k, v in obj.items()}
        if isinstance(obj, list):
            return [self._redact_json(v) for v in obj]
        if isinstance(obj, str):
            return self._redact_scalar(obj)
        return obj

    def appendix(self):
        data = self._redact_json(self.scan) if self.anonymize else self.scan
        raw = json.dumps(data, indent=2, ensure_ascii=False)
        truncated = len(raw) > 8000
        if truncated:
            raw = raw[:8000].rstrip() + "\n… (output truncated)"
        # wrap long lines (Preformatted preserves whitespace but does not wrap)
        raw = "\n".join(
            "\n".join(textwrap.wrap(ln, width=112, subsequent_indent="    ",
                                    break_long_words=True, break_on_hyphens=False))
            if len(ln) > 112 else ln
            for ln in raw.splitlines())
        raw = raw.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

        code = ParagraphStyle("code", parent=self.s["mono"], fontSize=6.5, leading=8.5,
                              textColor=MUTED)
        els = [PageBreak(), Paragraph("APPENDIX A · RAW SCAN DATA", self.s["h2"])]
        if self.anonymize:
            els.append(Paragraph("Email, phone, and URL values are redacted; usernames and "
                                 "display names are retained (consistent with the cover).",
                                 self.s["body"]))
        if truncated:
            els.append(Paragraph("Output capped at 8,000 characters.",
                                 ParagraphStyle("note", parent=self.s["body"], fontSize=7.5,
                                                textColor=MUTED)))
        els += [Spacer(1, 0.08 * inch), Preformatted(raw, code)]
        return els

