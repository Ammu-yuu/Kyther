def _register_fonts(font_dir="kyther/assets/fonts"):
    global FONT_TITLE, FONT_MONO
    import os
    for face, fname, target in [
        ("Quicksand", "Quicksand-Bold.ttf", "FONT_TITLE"),
        ("JetBrainsMono", "JetBrainsMono-Regular.ttf", "FONT_MONO"),
    ]:
        path = os.path.join(font_dir, fname)
        if os.path.exists(path):
            try:
                pdfmetrics.registerFont(TTFont(face, path))
                globals()[target] = face
            except Exception:
                pass


_register_fonts()

